/**
 * Starts the demo data over from scratch:
 *   - deletes EVERY client (sections, leads, uploaded images) and every user who is not a super admin,
 *   - creates one platform assistant,
 *   - rebuilds the platform's own site at "/" (PlatformSiteSeeder),
 *   - creates one example site per business kind in config/platform.php → business_kinds, each using all 15 section types
 *     and owned by one login.
 *
 *   php artisan db:seed --class="Database\Seeders\ExampleSitesSeeder"
 *
 * Every login it creates uses the password 12345. Super admins keep their own password.
 */
class ExampleSitesSeeder extends Seeder
{
    private const PASSWORD = '12345';

    public function run(Builder $b): void
    {
        if (! app()->environment('local', 'testing') && ! $this->command?->confirm('This DELETES every client and every non-admin user. Continue?')) {
            return;
        }

        $this->wipe();

        $assistant = User::create(['name' => 'Platform assistant', 'email' => 'assistant@erp.test', 'password' => self::PASSWORD]);
        $assistant->setPlatformRole('assistant');
        $this->command?->line('  assistant: assistant@erp.test / ' . self::PASSWORD);

        $this->call(PlatformSiteSeeder::class);

        foreach ($this->sites() as $kind => $d) {
            $this->site($b, $kind, $d);
        }

        Cache::flush(); // cached public pages of the deleted sites
        $this->command?->info('Done: ' . count($this->sites()) . ' example sites + the platform site at "/".');
    }

    // ------------------------------------------------------------------ wipe

    private function wipe(): void
    {
        foreach (Client::withTrashed()->pluck('id') as $id) {
            File::deleteDirectory(public_path("uploads/clients/{$id}"));
        }
        DB::transaction(function () {
            Submission::query()->delete();
            Section::query()->delete();
            DB::table('client_user')->delete();
            Client::withTrashed()->forceDelete();
            User::where('is_super_admin', false)->delete();
        });
        $this->command?->warn('  Deleted all clients and every user except the super admin(s).');
    }

