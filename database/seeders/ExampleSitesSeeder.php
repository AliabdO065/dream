    /** A generated picture (brand → accent gradient + soft shapes) in the client's upload folder; returns the stored path. */
    private function pic(Client $c, string $file, string $fromHex, string $toHex, int $w = 1200, int $h = 800, string $mark = ''): string
    {
        $dir = public_path("uploads/clients/{$c->id}");
        File::ensureDirectoryExists($dir);
        [$from, $to] = [sscanf($fromHex, '#%02x%02x%02x'), sscanf($toHex, '#%02x%02x%02x')];

        $im = imagecreatetruecolor($w, $h);
        for ($y = 0; $y < $h; $y++) {
            $t = $y / max(1, $h - 1);
            imageline($im, 0, $y, $w, $y, imagecolorallocate($im,
                (int) ($from[0] + ($to[0] - $from[0]) * $t), (int) ($from[1] + ($to[1] - $from[1]) * $t), (int) ($from[2] + ($to[2] - $from[2]) * $t)));
        }
        imagealphablending($im, true);
        $seed = crc32($c->slug . $file);
        for ($i = 0; $i < 6; $i++) {
            $r = (int) (($w * 0.10) + (($seed >> ($i * 3)) & 0xff) / 255 * $w * 0.22);
            $x = (int) ((($seed >> ($i * 2)) & 0xff) / 255 * $w);
            $y = (int) ((($seed >> ($i * 2 + 5)) & 0xff) / 255 * $h);
            imagefilledellipse($im, $x, $y, $r * 2, $r * 2, imagecolorallocatealpha($im, 255, 255, 255, 108 + ($i % 3) * 6));
        }
        if ($mark !== '') { // a large initial in the middle (logos, portraits)
            $small = imagecreatetruecolor(12, 16);
            imagefill($small, 0, 0, imagecolorallocate($small, 0, 0, 0));
            imagestring($small, 5, 2, 0, $mark, imagecolorallocate($small, 255, 255, 255));
            $mask = imagecreatetruecolor((int) ($w * 0.5), (int) ($w * 0.5 * 16 / 12));
            imagecopyresized($mask, $small, 0, 0, 0, 0, imagesx($mask), imagesy($mask), 12, 16);
            imagecopymerge($im, $mask, (int) (($w - imagesx($mask)) / 2), (int) (($h - imagesy($mask)) / 2), 0, 0, imagesx($mask), imagesy($mask), 55);
        }
        imagejpeg($im, "{$dir}/{$file}.jpg", 82);

        return "clients/{$c->id}/{$file}.jpg";
    }

